package it.polimi.ingsw.net.rmi.client;

import it.polimi.ingsw.net.events.clientevents.ClientEvent;
import it.polimi.ingsw.net.events.serverevents.PingEvent;
import it.polimi.ingsw.net.events.serverevents.ServerEvent;
import it.polimi.ingsw.net.rmi.server.RmiServerInterface;
import it.polimi.ingsw.view.ViewFlow;


import javax.swing.text.View;
import java.rmi.NoSuchObjectException;
import java.rmi.RemoteException;
import java.rmi.server.UnicastRemoteObject;

/**
 * RMI client implementation that communicates with the RMI server using remote method invocation.
 * Extends UnicastRemoteObject to expose remote methods callable by the server.
 * This class handles outgoing client events by invoking the remote method on the RMI server stub,
 * which in turn updates the game model through the server-side architecture.
 * Simultaneously, it exposes methods invoked remotely by the server, allowing the server
 * to update the client's view.
 *
 */
public class RmiClient extends UnicastRemoteObject implements RemoteClientHandler  {

    /**
     * rmi Server stub
     */
    private final RmiServerInterface server;

    /**
     * client's view
     */
    private final ViewFlow view;

    /**
     * client's id
     */
    private int id;

    /**
     * Constructs the RMI client, binding it to the specified server interface and view.
     *
     * @param server remote RMI server stub used to invoke server-side methods
     * @param view client-side view responsible for updating the user interface
     * @throws RemoteException if export fails or communication issues occur
     */
    public RmiClient(RmiServerInterface server, ViewFlow view) throws RemoteException {
        super();
        this.server = server;
        this.view = view;
        this.id = -1;
    }

    /**
     * Invoked remotely by the server update the client's view
     *
     * @param event event generated by the server which contains information to update the view
     * @throws RemoteException if remote invocation fails
     */
    @Override
    public void handleIncomingEvent(ServerEvent event) throws RemoteException {
        view.onEventReceived(event);
    }

    /**
     * Invokes a remote method on the server stub which starts the thread that handles
     * the event containing client's data or actions in order to update the model
     *
     * @param event event generated by the client with data or actions
     * @throws RemoteException if remote invocation fails
     */
    @Override
    public void handleOutgoingEvent (ClientEvent event) throws RemoteException {
        server.handleIncomingEvent(event, this);
    }

    /**
     * Responds to a ping event from the server, used to verify client availability
     *
     * @param event ping event from the server
     * @throws RemoteException if remote invocation fails
     */
    @Override
    public void respondToPing(PingEvent event) throws RemoteException{
        view.onEventReceived(event);
    }

    /**
     * Unexports this remote object to clean up resources and
     * terminate its ability to receive remote calls.
     * Logs any error if unexporting fails.
     *
     * @throws RemoteException if remote operation fails
     */
    @Override
    public void close() throws RemoteException {
        try {
            UnicastRemoteObject.unexportObject(this, true);
        } catch (NoSuchObjectException e) {
            System.err.println("Failed to unexport RMI client: " + e.getMessage());
        }
    }

    /**
     * Sets the unique identifier for this client instance.
     * Can only be set once; subsequent calls have no effect.
     *
     * @param id unique client ID assigned by the server
     * @throws RemoteException if remote invocation fails
     */
    @Override
    public void setId(int id) throws RemoteException {
        if (this.id == -1){
            this.id = id;
        }
    }

    /**
     * Retrieves the unique identifier assigned to this client instance.
     *
     * @return client ID
     * @throws RemoteException if remote invocation fails
     */
    @Override
    public int getId() throws RemoteException {
        return id;
    }


}
